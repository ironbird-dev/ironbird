export const MATERIALS = ['TASK.md', 'CHECKLIST.md', 'RESULTS.md', 'acceptance.yaml'];

/** Limits for one proxy session, startup to the end of teardown. Integration, installs, and two bundles take longer than M3's fix. */
export const BUDGET_USD = 20;
export const SESSION_LIMIT_MS = 90 * 60_000;
export const TEARDOWN_RESERVE_MS = 2 * 60_000;
/** The daemon's default ports and Metro's. They must be free before a session: the agent starts its own daemon on the defaults. */
export const PORTS = [4567, 4568, 8081];

/** <eval home>/proxy */
export function proxyHome(env = process.env) {
  return path.join(evalHome(env), 'proxy');
}

export function proxyLayout(home = proxyHome()) {
  return {
    home,
    template: path.join(home, 'template'),
    templateCheck: path.join(home, 'template-check'),
    templateGrade: path.join(home, 'template-grade'),
    docs: path.join(home, 'docs'),
    baselineDir: path.join(home, 'baseline'),
    baselineFile: path.join(home, 'baseline.json'),
    prepareFile: path.join(home, 'prepare.json'),
    logs: path.join(home, 'logs'),
    sessions: path.join(home, 'sessions'),
    grades: path.join(home, 'grades'),
  };
}

/** One session: the agent works in project/ and reads docs/; the harness keeps its own files beside them. */
export function proxySessionLayout(home, id) {
  const dir = path.join(home, 'sessions', id);
  return {
    dir,
    project: path.join(dir, 'project'),
    docs: path.join(dir, 'docs'),
    transcript: path.join(dir, 'transcript.jsonl'),
    stderr: path.join(dir, 'claude-stderr.log'),
    settings: path.join(dir, 'settings.json'),
    record: path.join(dir, 'session.json'),
    logs: path.join(dir, 'logs'),
  };
}

/** One grade under `root`: a copy of the session's project, the grader's outputs, and the verdict. */
export function proxyGradeLayout(root, id) {
  const dir = path.join(path.resolve(root), id);
  return { dir, session: path.join(dir, 'session'), out: path.join(dir, 'grader'), grade: path.join(dir, 'grade.json'), report: path.join(dir, 'final-report.md') };
}

/** Repository paths the template is built from: run-session refuses a template prepared before any of them changed. */
export const PROXY_SOURCES = ['examples/bare-redux/integration-exercise', 'examples/bare-redux/eval', 'packages', 'docs', 'README.md', 'pnpm-lock.yaml'];
